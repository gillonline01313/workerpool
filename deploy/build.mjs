// Builds dist/: the public website plus one compiled _worker.js that does what the functions/ folder does
// (same URL routing, same handlers), so the site can be deployed to Cloudflare Pages without GitHub:
// Workers & Pages → your project → Create deployment → upload dist.zip (drag and drop supports _worker.js).
// Run:  node deploy/build.mjs      (needs esbuild; output: dist/ and dist.zip)
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";

const ROOT = path.resolve(new URL("..", import.meta.url).pathname);
const OUT = path.join(ROOT, "dist");
// Never published: server code, build scripts, the Android signing key, database schemas, docs.
const SKIP = [/^\.git(\/|$)/, /^\.github\//, /^functions\//, /^scripts\//, /^android\//, /^deploy\//, /^cron\//, /^dist(\/|\.zip$)/, /^tools\/src\//,
  /^schema.*\.sql$/, /^README\.md$/, /^\.gitignore$/, /__pycache__/, /\.py$/, /^_headers$/, /^_redirects$/, /\.DS_Store$/];

/* ---------- 1. routes from functions/ (Cloudflare Pages file-based routing) ---------- */
const files = [];
(function walk(d) { for (const f of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, f.name); if (f.isDirectory()) walk(p); else if (/\.js$/.test(f.name)) files.push(p); } })(path.join(ROOT, "functions"));
const routes = files.map((f) => path.relative(path.join(ROOT, "functions"), f).replace(/\\/g, "/"))
  .filter((r) => !r.split("/").some((s) => s.startsWith("_")))          // _lib.js etc. are helpers, not routes
  .map((r) => {
    const segs = r.replace(/\.js$/, "").split("/");
    if (segs[segs.length - 1] === "index") segs.pop();
    const parts = segs.map((s) => { let m;
      if ((m = s.match(/^\[\[(\w+)\]\]$/))) return { all: m[1] };
      if ((m = s.match(/^\[(\w+)\]$/))) return { one: m[1] };
      return { lit: s }; });
    return { file: r, parts };
  })
  // most specific first: more literal segments, then fewer wildcards
  .sort((a, b) => b.parts.filter((p) => p.lit).length - a.parts.filter((p) => p.lit).length || a.parts.filter((p) => p.all).length - b.parts.filter((p) => p.all).length);

/* ---------- 2. _headers and _redirects (applied by the worker so they still work) ---------- */
const headerRules = []; let cur = null;
for (const line of fs.readFileSync(path.join(ROOT, "_headers"), "utf8").split(/\r?\n/)) {
  if (!line.trim() || line.trim().startsWith("#")) continue;
  if (!/^\s/.test(line)) { cur = { pat: line.trim(), set: {} }; headerRules.push(cur); }
  else if (cur) { const i = line.indexOf(":"); cur.set[line.slice(0, i).trim()] = line.slice(i + 1).trim(); }
}
const redirects = fs.readFileSync(path.join(ROOT, "_redirects"), "utf8").split(/\r?\n/).map((l) => l.trim()).filter((l) => l && !l.startsWith("#")).map((l) => { const [from, to, code] = l.split(/\s+/); return { from, to, code: +(code || 302) }; });

/* ---------- 3. the worker entry ---------- */
const entry = `// Generated by deploy/build.mjs. Do not edit: change functions/ and rebuild.
${routes.map((r, i) => `import * as m${i} from ${JSON.stringify("../functions/" + r.file)};`).join("\n")}
const ROUTES = [${routes.map((r, i) => `[${JSON.stringify(r.parts)}, m${i}]`).join(",\n  ")}];
const HEADERS = ${JSON.stringify(headerRules)};
const REDIRECTS = ${JSON.stringify(redirects)};
const glob = (pat, p) => new RegExp("^" + pat.replace(/[.+?^\${}()|[\\]\\\\]/g, "\\\\$&").replace(/\\*/g, ".*") + "$").test(p);
function match(parts, segs) {
  const params = {};
  for (let i = 0; i < parts.length; i++) {
    const p = parts[i];
    if (p.all) { const rest = segs.slice(i); if (!rest.length) return null; params[p.all] = rest; return params; }
    if (i >= segs.length) return null;
    if (p.lit !== undefined) { if (p.lit !== segs[i]) return null; }
    else params[p.one] = segs[i];
  }
  return segs.length === parts.length ? params : null;
}
function withHeaders(res, pathname) {
  const add = HEADERS.filter((h) => glob(h.pat, pathname));
  if (!add.length) return res;
  const r = new Response(res.body, res);
  for (const h of add) for (const [k, v] of Object.entries(h.set)) r.headers.set(k, v);
  return r;
}
export default {
  async fetch(request, env, ctx) {
    const url = new URL(request.url), pathname = url.pathname;
    for (const r of REDIRECTS) if (glob(r.from, pathname)) return Response.redirect(new URL(r.to, url).toString(), r.code);
    const segs = pathname.split("/").filter(Boolean).map((s) => { try { return decodeURIComponent(s); } catch { return s; } });
    const assets = () => env.ASSETS.fetch(request);
    for (const [parts, mod] of ROUTES) {
      const params = match(parts, segs);
      if (!params) continue;
      const m = request.method.charAt(0) + request.method.slice(1).toLowerCase();
      const fn = mod["onRequest" + m] || mod.onRequest;
      if (!fn) break;                                   // no handler for this method: same as Pages, fall through to the files
      const res = await fn({ request, env, params, data: {}, waitUntil: (p) => ctx.waitUntil(p), passThroughOnException: () => {}, next: assets, functionPath: pathname });
      return withHeaders(res, pathname);
    }
    return withHeaders(await assets(), pathname);
  },
};
`;
fs.rmSync(OUT, { recursive: true, force: true }); fs.mkdirSync(OUT);
const tmp = path.join(ROOT, "deploy", ".entry.mjs");
fs.writeFileSync(tmp, entry);
const esbuild = process.env.ESBUILD || "esbuild";
execFileSync(esbuild, [tmp, "--bundle", "--format=esm", "--platform=neutral", "--target=es2022", "--main-fields=module,main", "--outfile=" + path.join(OUT, "_worker.js")], { stdio: "inherit" });
fs.rmSync(tmp);
// the scheduled-jobs Worker (cron/), as one file you can paste into the Cloudflare dashboard editor
fs.mkdirSync(path.join(ROOT, "cron", "dist"), { recursive: true });
execFileSync(esbuild, [path.join(ROOT, "cron", "worker.js"), "--bundle", "--format=esm", "--platform=neutral", "--target=es2022", "--main-fields=module,main", "--outfile=" + path.join(ROOT, "cron", "dist", "worker.js")], { stdio: "inherit" });

/* ---------- 4. public files ---------- */
let n = 0;
(function copy(d) { for (const f of fs.readdirSync(d, { withFileTypes: true })) {
  const p = path.join(d, f.name), rel = path.relative(ROOT, p).replace(/\\/g, "/");
  if (SKIP.some((re) => re.test(rel))) continue;
  if (f.isDirectory()) copy(p); else { fs.mkdirSync(path.dirname(path.join(OUT, rel)), { recursive: true }); fs.copyFileSync(p, path.join(OUT, rel)); n++; }
} })(ROOT);
fs.rmSync(path.join(ROOT, "dist.zip"), { force: true });
execFileSync("zip", ["-qr", path.join(ROOT, "dist.zip"), "."], { cwd: OUT });
console.log(`dist/: ${n} public files + _worker.js (${routes.length} routes). dist.zip ready to upload.`);
